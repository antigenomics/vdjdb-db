def _fill(column: str) -> str:
    for prefix, colour in GROUP_FILLS:
        if column.startswith(prefix):
            return colour
    return REQUIRED_FILL


def header_line() -> str:
    """The template's header, which is :data:`CHUNK_COLUMNS` and nothing else."""
    return "\t".join(CHUNK_COLUMNS)


def write_tsv(path: Path, examples: Sequence[dict[str, str]] = ()) -> Path:
    """The tab-separated template."""
    rows = [header_line()]
    rows += ["\t".join(row.get(c, "") for c in CHUNK_COLUMNS) for row in examples]
    path.write_text("\n".join(rows) + "\n")
    return path


def write_xlsx(path: Path, examples: Sequence[dict[str, str]] = ()) -> Path:
    """The Excel template: text-formatted cells, group-coloured header, and a column guide."""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    book = Workbook()
    sheet = book.active
    sheet.title = "chunk"
    for i, column in enumerate(CHUNK_COLUMNS, start=1):
        cell = sheet.cell(row=1, column=i, value=column)
        cell.fill = PatternFill("solid", fgColor=_fill(column))
        cell.font = Font(bold=True)
        cell.alignment = Alignment(horizontal="left")
        # The registry's own description, as the note Excel shows on hover.
        if comment := FIELDS[column].comment:
            cell.comment = _note(comment)
        sheet.column_dimensions[get_column_letter(i)].width = max(11, min(len(column) + 2, 24))
    if examples is EXAMPLES and len(EXAMPLE_NOTES) != len(EXAMPLES):
        raise AssertionError("EXAMPLE_NOTES and EXAMPLES must be parallel")
    for r, row in enumerate(examples, start=2):
        for i, column in enumerate(CHUNK_COLUMNS, start=1):
            sheet.cell(row=r, column=i, value=row.get(column, ""))
        if examples is EXAMPLES:
            sheet.cell(row=r, column=1).comment = _note(EXAMPLE_NOTES[r - 2])
    # Text on every cell of every column, including the empty rows a submitter will type into.
    # `number_format` is per cell in openpyxl, so the range has to cover more than the examples.
    for row in sheet.iter_rows(min_row=1, max_row=len(examples) + 1 + BLANK_ROWS,
                               max_col=len(CHUNK_COLUMNS)):
        for cell in row:
            cell.number_format = "@"
    sheet.freeze_panes = "A2"

    guide = book.create_sheet("columns")
    guide.append([f"How to fill each column: {SPECIFICATION}"])
    guide["A1"].font = Font(bold=True)
    guide.append([])
    guide.append(["column", "group", "description"])
    for cell in guide[3]:
        cell.font = Font(bold=True)
    for column in CHUNK_COLUMNS:
        group = ("required" if _fill(column) == REQUIRED_FILL
                 else "method" if column.startswith("method.")
                 else "meta" if column.startswith("meta.") else "curation")
        guide.append([column, group, FIELDS[column].comment])
    guide.column_dimensions["A"].width = 24
    guide.column_dimensions["B"].width = 10
    guide.column_dimensions["C"].width = 110
    for row in guide.iter_rows(min_row=4, min_col=3, max_col=3):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")

    book.save(path)
    return path


def _note(text: str):
    from openpyxl.comments import Comment

    note = Comment(text, "vdjdb")
    note.width, note.height = 400, 120
    return note
