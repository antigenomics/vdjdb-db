"""The submission template, generated from the field registry.

Two files, one declaration. ``template.tsv`` is the machine-readable form; ``template.xlsx`` is the
one most submitters open, and it carries the three things a plain `.tsv` cannot:

* **every cell formatted as Text.** This is not decoration. ``method.frequency`` holds `50/67` and a
  V call holds `TRAV12-2*01`; Excel turns the first into a date and can mangle the second the moment
  a column is typed as General. The retired `template.xls` protected them exactly this way - all 165
  of its data cells carried number format ``@`` - and losing that protection is how a submission
  arrives with a column of 1967 dates in it.
* **the header coloured by column group**, which is how a submitter sees at a glance which columns
  are required. The four colours are read off the retired `template.xls` so the file looks like the
  one people have been using since 2016, not like a new one.
* **a second sheet describing every column**, from the registry's own ``comment``, so the
  description cannot drift from the build the way the old spreadsheet's did.

The retired `.xls` was a 2016 `Composite Document File V2`, code page 1251, readable only with
`xlrd`. It was one of the nine places this package's docstring lists as having already drifted, and
it had: its examples wrote ``antigen.species = HIV`` where the vocabulary now says ``HIV-1``.
"""
